def gen_detector_config(cfg, dcfg):
    d = dcfg["detector"]
    fr = dcfg["frame"]
    det = D.CombDetector(cfg)
    n_f0 = len(det.f0s)

    # Cross-check: the Config the tables came from must equal device_config.
    live = cfg.to_dict()
    drift = {k: (live[k], v) for k, v in d.items()
             if k in live and live[k] != v}
    if drift:
        raise SystemExit(f"device_config.json disagrees with the committed "
                         f"Config: {drift}")

    L = [BANNER, "#pragma once", "#include <stdint.h>", ""]
    L.append("// ---- identity -------------------------------------------")
    L.append(f'#define SENTRY_SITE            "{dcfg["site"]}"')
    L.append(f'#define SENTRY_CORPUS_TAG      "{dcfg["corpus_tag"]}"')
    L.append(f'#define SENTRY_CONFIG_SCHEMA   "{dcfg["schema"]}"')
    L.append("")
    L.append("// ---- the two operating points ---------------------------")
    L.append("// NORMAL_THRESHOLD is the PARITY point: the golden vectors were")
    L.append("// cut at it and the port is judged against it.")
    L.append("// DEFAULT_THRESHOLD is the DEPLOYMENT default (HIGH_ALERT); it")
    L.append("// is not exercised by the golden vectors. Two names, on")
    L.append("// purpose - conflating them would silently rejudge the port.")
    L.append(f'#define SENTRY_DEFAULT_PRESET  "{dcfg["default_preset"]}"')
    L.append(f'#define NORMAL_THRESHOLD       '
             f'{f64(dcfg["presets"]["NORMAL"]["threshold"])}')
    L.append(f'#define HIGH_ALERT_THRESHOLD   '
             f'{f64(dcfg["presets"]["HIGH_ALERT"]["threshold"])}')
    L.append(f'#define DEFAULT_THRESHOLD      HIGH_ALERT_THRESHOLD')
    L.append(f'#define GOLDEN_THRESHOLD       NORMAL_THRESHOLD')
    L.append("")
    L.append("// ---- frame geometry -------------------------------------")
