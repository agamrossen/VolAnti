def _decimal(s):
    """Force a floating-point token. "%.9g" of 0.0 is "0", and "0f" is an
    invalid integer suffix, not a float."""
    if not any(c in s for c in ".eEnif"):
        s += ".0"
    return s


def f32(x):
    """A C float literal that round-trips to exactly this float32."""
    v = np.float32(x)
    if not np.isfinite(v):
        raise ValueError(f"non-finite constant {x}")
    return _decimal(f"{float(v):.9g}") + "f"


def f64(x):
    if not np.isfinite(x):
        raise ValueError(f"non-finite constant {x}")
    return _decimal(f"{float(x):.17g}")


def emit_array(name, values, ctype, fmt, per_line, extra="static const"):
    out = [f"{extra} {ctype} {name}[{len(values)}] = {{"]
    line = " "
    for i, v in enumerate(values):
        tok = fmt(v) + ","
        if len(line) + len(tok) > 78:
            out.append(line)
            line = " "
        line += " " + tok
    if line.strip():
        out.append(line)
    out.append("};")
    return "\n".join(out)


